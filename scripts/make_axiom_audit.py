#!/usr/bin/env python3
"""Regenerate CheckAxioms.lean for public theorem and lemma declarations in this project."""
from pathlib import Path
import argparse
import re

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check-only', action='store_true',
                    help='Check source declarations without replacing CheckAxioms.lean')
args = parser.parse_args()


def without_comments(text):
    result, i, depth = [], 0, 0
    while i < len(text):
        if text.startswith('/-', i):
            depth += 1
            result.append('  ')
            i += 2
        elif depth and text.startswith('-/', i):
            depth -= 1
            result.append('  ')
            i += 2
        elif depth:
            result.append('\n' if text[i] == '\n' else ' ')
            i += 1
        elif text.startswith('--', i):
            end = text.find('\n', i)
            if end == -1:
                break
            result.append(' ' * (end - i))
            i = end
        else:
            result.append(text[i])
            i += 1
    if depth:
        raise ValueError('Unclosed Lean comment')
    return ''.join(result)


names = []
proof_directory = root / 'DepthAspect'
proof_paths = sorted(proof_directory.rglob('*.lean'))
if any(path.parent != proof_directory for path in proof_paths):
    raise ValueError('Nested proof sources are unsupported; no file may be omitted from the audit.')
for path in proof_paths:
    stack = []
    source = without_comments(path.read_text())
    if re.search(r'\b(sorry|admit|axiom|native_decide|unsafe)\b', source):
        raise ValueError(f'Forbidden proof placeholder or shortcut in {path.name}')
    for line in source.splitlines():
        line = line.strip()
        match = re.match(r'namespace\s+(\S+)', line)
        if match:
            stack.append(('namespace', match.group(1)))
            continue
        if re.match(r'(noncomputable\s+)?section(?:\s|$)', line):
            stack.append(('section', ''))
            continue
        if re.fullmatch(r'end(?:\s+\S+)?', line):
            if not stack:
                raise ValueError(f'Unmatched end in {path.name}')
            stack.pop()
            continue
        match = re.match(r'(?:@\[[^\]]*\]\s*)?(?:(private|protected)\s+)?(?:theorem|lemma)\s+([^\s(:]+)', line)
        if match and match.group(1) != 'private':
            namespace = '.'.join(n for kind, n in stack if kind == 'namespace')
            names.append(namespace + '.' + match.group(2) if namespace else match.group(2))
    # Lean permits a file-wide noncomputable section to remain open at EOF.
    # Sections add no name prefix, so they do not affect the theorem inventory.
    if any(kind == 'namespace' for kind, _ in stack):
        raise ValueError(f'Unclosed namespace in {path.name}')

if len(names) != len(set(names)):
    raise ValueError('Duplicate parsed public theorem names')
out = ['import DepthAspect', '', '/- Generated by scripts/make_axiom_audit.py. -/', '']
out += ['#print axioms ' + name for name in names]
if args.check_only:
    print(f'Checked source inventory for {len(names)} public theorems; no audit file changed.')
else:
    (root / 'CheckAxioms.lean').write_text('\n'.join(out) + '\n')
    print(f'Generated axiom audit for {len(names)} public theorems.')
